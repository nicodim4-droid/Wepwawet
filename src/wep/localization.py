def translate(language: str, key: str, **values: object) -> str:
    """Return a localized UI string, formatted with its supplied values."""
    return STRINGS[language][key].format(**values)


def translate_known_message(message: str, language: str) -> str:
    """Translate a known diagnostic message while preserving its details."""
    for key, template in STRINGS["ru"].items():
        if not key.startswith("error_"):
            continue
        fields = [
            field_name
            for _, field_name, _, _ in string.Formatter().parse(template)
            if field_name
        ]
        if not fields:
            if template == message:
                return STRINGS[language][key]
            continue

        pattern = re.escape(template)
        for field_name in fields:
            pattern = pattern.replace(
                re.escape("{" + field_name + "}"),
                f"(?P<{field_name}>.+?)",
            )
        match = re.fullmatch(pattern, message, flags=re.DOTALL)
        if match:
            return translate(language, key, **match.groupdict())
    return message
